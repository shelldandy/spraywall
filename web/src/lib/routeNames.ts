function pick<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function possessive(name: string): string {
  return name.endsWith("s") ? `${name}'` : `${name}'s`;
}

const TEMPLATES: (() => string)[] = [
  () => `The ${pick(ADJECTIVES)} ${pick(NOUNS)}`,
  () => `${pick(ADJECTIVES)} ${pick(NOUNS)}`,
  () => `${pick(NOUNS)} ${pick(NOUNS)}`,
  () => `${pick(GERUNDS)} with ${pick(NOUNS)}s`,
  () => pick(PUNS),
  () => `${possessive(pick(CLIMBERS))} ${pick(NOUNS)}`,
  () => `${pick(ADJECTIVES)} ${pick(CLIMBERS)}`,
  () => `${pick(CLIMBERS)} Would Flash This`,
  () => `Not ${possessive(pick(CLIMBERS))} Beta`,
  () => `${pick(GERUNDS)} with ${pick(CLIMBERS)}`,
];

/** Random climbing-flavored route name; never returns `previous` so regenerating always changes. */
export function generateRouteName(previous?: string): string {
  let name = pick(TEMPLATES)();
  while (name === previous) name = pick(TEMPLATES)();
  return name;
}
